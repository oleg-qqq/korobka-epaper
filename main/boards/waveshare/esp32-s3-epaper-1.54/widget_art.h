// Данные погоды. Лежат здесь, чтобы их видели и плата, и дисплей.
struct WeatherDay {
    int day = 0;          // число месяца
    int code = 0;         // код погоды Open-Meteo
    float tmax = 0.0f;    // максимум за день
};

struct WeatherCache {
    std::string summary;          // готовая фраза для голоса
    float temperature = 0.0f;
    int weather_code = 0;
    int humidity = 0;             // проценты
    WeatherDay days[3];           // прогноз на три следующих дня
    bool has_days = false;
    int64_t fetched_at_ms = 0;     // время работы в момент получения (для кэша)
    int64_t fetched_at_unix = 0;   // настоящее время получения, 0 если неизвестно
    bool valid = false;
};

// Прогноз по часам и солнце. Заполняется при запросе погоды, лежит в
// RTC-памяти, поэтому переживает глубокий сон.
#define FC_HOURS 96          // сутки назад и трое суток вперёд, по часу
#define FC_DAYS 5            // вчера, сегодня и три дня вперёд
#define FC_NO_TEMP (-32768)  // нет данных о температуре
#define FC_NO_VALUE 255      // нет данных (дождь, УФ)

struct ForecastExtra {
    uint32_t magic;
    int64_t hourly_start;             // время первого часа (unix)
    int16_t hourly_t10[FC_HOURS];     // температура x10
    uint8_t hourly_rain[FC_HOURS];    // вероятность дождя, %
    int64_t day_start[FC_DAYS];       // начало суток (unix)
    int64_t sunrise[FC_DAYS];
    int64_t sunset[FC_DAYS];
    uint8_t uv10[FC_DAYS];            // УФ-индекс x10
};

// Воздух (Open-Meteo Air Quality). Лежит в RTC-памяти.
#define AQ_HOURS 48
#define AQ_NONE 0xFFFF       // нет данных
struct AirCache {
    uint32_t magic;
    int64_t fetched_unix;             // когда получено
    uint16_t aqi;                     // европейский индекс качества воздуха
    uint16_t pm10_10;                 // PM10, мкг/м3 x10
    uint16_t pm25_10;                 // PM2.5, мкг/м3 x10
    uint16_t dust;                    // пыль (песок из Сахары), мкг/м3
    uint16_t uv10;                    // УФ-индекс сейчас x10
    int64_t hour0;                    // час первой точки прогноза
    uint16_t dust_next[AQ_HOURS];     // пыль по часам, мкг/м3
    uint16_t pm10_next[AQ_HOURS];     // PM10 по часам x10
};

// Море (Open-Meteo Marine). Лежит в RTC-памяти.
#define SEA_HOURS 48
struct SeaCache {
    uint32_t magic;
    int64_t fetched_unix;
    int16_t sst10;                    // температура воды x10, AQ_NONE-подобное: -32768 нет
    uint16_t wave_cm;                 // высота волн сейчас, см
    uint16_t wave_max_cm;             // максимум волн сегодня, см
    uint16_t period10;                // период волн, с x10
    int64_t hour0;
    uint16_t wave_next_cm[SEA_HOURS]; // волны по часам, см
};

static constexpr uint32_t kAirMagic = 0x41495231;   // "AIR1"
static constexpr uint32_t kSeaMagic = 0x53454131;   // "SEA1"

// Можно ли купаться: 2 отлично, 1 можно, 0 не стоит, -1 неизвестно.
static inline int SeaVerdict(const SeaCache& s) {
    if (s.magic != kSeaMagic || s.sst10 == -32768) return -1;
    float water = s.sst10 / 10.0f;
    float wave = (s.wave_cm == AQ_NONE) ? 0.0f : s.wave_cm / 100.0f;
    if (water >= 22.0f && wave < 0.6f) return 2;
    if (water >= 19.0f && wave < 1.2f) return 1;
    return 0;
}

// Категория европейского индекса: 0 отлично ... 5 ужасно, -1 нет данных.
static inline int AqiLevel(int aqi) {
    if (aqi < 0 || aqi == AQ_NONE) return -1;
    if (aqi < 20) return 0;
    if (aqi < 40) return 1;
    if (aqi < 60) return 2;
    if (aqi < 80) return 3;
    if (aqi < 100) return 4;
    return 5;
}


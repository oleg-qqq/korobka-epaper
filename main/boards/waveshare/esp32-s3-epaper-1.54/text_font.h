// Ищет глиф по коду (таблица отсортирована), nullptr если нет.
static inline const EpdTextGlyph* FindTextGlyph(uint32_t cp) {
    int lo = 0, hi = kTextFontCount - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if (kTextFont[mid].cp == cp) return &kTextFont[mid];
        if (kTextFont[mid].cp < cp) lo = mid + 1; else hi = mid - 1;
    }
    return nullptr;
}

// Следующий символ из строки UTF-8. Сдвигает указатель. 0 в конце строки.
static inline uint32_t Utf8Next(const char*& p) {
    const unsigned char* s = (const unsigned char*)p;
    if (*s == 0) return 0;
    uint32_t cp;
    int extra;
    if (s[0] < 0x80) { cp = s[0]; extra = 0; }
    else if ((s[0] & 0xE0) == 0xC0) { cp = s[0] & 0x1F; extra = 1; }
    else if ((s[0] & 0xF0) == 0xE0) { cp = s[0] & 0x0F; extra = 2; }
    else if ((s[0] & 0xF8) == 0xF0) { cp = s[0] & 0x07; extra = 3; }
    else { p++; return '?'; }
    int i = 1;
    for (; i <= extra; i++) {
        if ((s[i] & 0xC0) != 0x80) { p += i; return '?'; }
        cp = (cp << 6) | (s[i] & 0x3F);
    }
    p += i;
    return cp;
}

// Сколько символов в строке UTF-8.
static inline int Utf8Len(const char* s) {
    int n = 0;
    while (Utf8Next(s) != 0) n++;
    return n;
}

